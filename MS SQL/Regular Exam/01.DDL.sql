CREATE DATABASE [EuroLeagues]

GO

USE [EuroLeagues]

GO

CREATE TABLE [Leagues]
(
	[Id] INT PRIMARY KEY IDENTITY,
	[Name] NVARCHAR(50) NOT NULL
)

GO

CREATE TABLE [Teams]
(
	[Id] INT PRIMARY KEY IDENTITY,
	[Name] NVARCHAR(50) UNIQUE NOT NULL,
	[City] NVARCHAR(50) NOT NULL,
	[LeagueId] INT NOT NULL FOREIGN KEY REFERENCES [Leagues]([Id])
)

GO

CREATE TABLE [Players]
(
	[Id] INT PRIMARY KEY IDENTITY,
	[Name] NVARCHAR(100) NOT NULL,
	[Position] NVARCHAR(20) NOT NULL
)

GO

CREATE TABLE [Matches]
(
	[Id] INT PRIMARY KEY IDENTITY,
	[HomeTeamId] INT NOT NULL FOREIGN KEY REFERENCES [Teams]([Id]),
	[AwayTeamId] INT NOT NULL FOREIGN KEY REFERENCES [Teams]([Id]),
	[MatchDate] DATETIME2 NOT NULL,
	[HomeTeamGoals] INT DEFAULT 0 NOT NULL,
	[AwayTeamGoals] INT DEFAULT 0 NOT NULL,
	[LeagueId] INT NOT NULL FOREIGN KEY REFERENCES [Leagues]([Id])
)

GO

CREATE TABLE [PlayersTeams]
(
	[PlayerId] INT UNIQUE NOT NULL FOREIGN KEY REFERENCES [Players]([Id]),
	[TeamId] INT NOT NULL FOREIGN KEY REFERENCES [Teams]([Id]),
	PRIMARY KEY ([PlayerId], [TeamId])
)

GO

CREATE TABLE [PlayerStats]
(
	[PlayerId] INT UNIQUE NOT NULL FOREIGN KEY REFERENCES [Players]([Id]),
	[Goals] INT DEFAULT 0 NOT NULL,
	[Assists] INT DEFAULT 0 NOT NULL,
	PRIMARY KEY ([PlayerId])
)

GO

CREATE TABLE [TeamStats]
(
	[TeamId] INT UNIQUE NOT NULL FOREIGN KEY REFERENCES [Teams]([Id]),
	[Wins] INT DEFAULT 0 NOT NULL,
	[Draws] INT DEFAULT 0 NOT NULL,
	[Losses] INT DEFAULT 0 NOT NULL,
	PRIMARY KEY ([TeamId])
)

GO